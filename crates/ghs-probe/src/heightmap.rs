//! Height-map grid, probing plan, and bilinear result matrix.

use ghs_core::{Axis, Position, ProbeResult};
use ghs_viewer::{Bounds2, Point2, Point3, Segment, Toolpath};

use crate::ProbePlan;
use crate::error::{ProbeError, ValidationError};
use crate::gcode::GcodeBuilder;
use crate::params::{
    ProbeParams, XyPoint, check_coordinate, check_finite, check_range, feature_to_controlled,
    validate_probe_offset,
};

/// Largest number of height-map points in one grid.
pub const MAX_HEIGHT_MAP_POINTS: usize = 4_096;

/// Largest accepted absolute height-map Z offset, in millimetres.
///
/// The offset is a constant datum shift added to every measured sample when
/// the map is used for display or compensation. The stored samples remain raw.
pub const MAX_HEIGHT_MAP_Z_OFFSET_MM: f64 = 1_000.0;

/// Largest number of columns or rows in a height map.
pub const MAX_HEIGHT_MAP_AXIS_POINTS: u16 = 128;

/// Upper bound on the segments generated by [`HeightMap::compensate_toolpath`]
/// when subdividing long moves.
///
/// Every input segment is always represented by at least one output segment.
/// Once the budget is exhausted, the remaining input segments are copied as a
/// single piece; they still receive endpoint compensation when both endpoints
/// have values, but they are not subdivided further, so a capped result never
/// drops motion or truncates the path.
pub const MAX_COMPENSATED_SEGMENTS: usize = 1_000_000;

/// Fraction of the smaller grid step used as the maximum sample spacing along
/// a compensated move.
const COMPENSATION_SAMPLE_FRACTION: f64 = 0.5;

/// Estimated fixed overhead per height-map point, in seconds.
///
/// Covers the relative retract, the move to safe Z, the rapid to the next point
/// and the descent to the search start. It is an estimate for the preflight
/// sheet, not a controller timing model.
pub const HEIGHT_MAP_POINT_OVERHEAD_SECONDS: f64 = 3.0;

const MAX_STEP_MM: f64 = 1_000.0;

/// A rectangular height-map grid.
///
/// Grid points are **feature / probe-tip** XY positions in machine
/// millimetres. [`HeightMapGrid::plan_with_offset`] subtracts a probe-tip
/// offset from every point to obtain the commanded controlled-point position;
/// [`HeightMapGrid::plan`] uses a zero offset.
#[derive(Debug, Clone, PartialEq)]
pub struct HeightMapGrid {
    /// First point, in machine millimetres, in feature/probe-tip coordinates.
    pub origin_mm: XyPoint,
    /// Column spacing, in millimetres.
    pub step_x_mm: f64,
    /// Row spacing, in millimetres.
    pub step_y_mm: f64,
    /// Number of columns, at least two.
    pub columns: u16,
    /// Number of rows, at least two.
    pub rows: u16,
    /// Lowest expected surface Z, in machine millimetres, used as every search
    /// target.
    ///
    /// Height-map probes travel from [`ProbeParams::safe_z_mm`] down to this
    /// target, so the rapid plane is above every point regardless of local
    /// height. Set [`ProbeParams::safe_z_mm`] above the highest point on the
    /// grid and keep `safe_z - surface_z` within
    /// [`ProbeParams::search_distance_mm`].
    pub surface_z_mm: f64,
}

impl HeightMapGrid {
    /// Number of points in the grid.
    #[must_use]
    pub fn point_count(&self) -> usize {
        usize::from(self.columns) * usize::from(self.rows)
    }

    /// Validate the grid bounds and size.
    pub fn validate(&self) -> Result<(), ValidationError> {
        check_coordinate("origin X", self.origin_mm.x_mm)?;
        check_coordinate("origin Y", self.origin_mm.y_mm)?;
        check_range("step_x_mm", self.step_x_mm, 0.0, MAX_STEP_MM)?;
        check_range("step_y_mm", self.step_y_mm, 0.0, MAX_STEP_MM)?;
        if self.step_x_mm <= 0.0 {
            return Err(ValidationError::NotPositive {
                field: "step_x_mm",
                value: self.step_x_mm,
            });
        }
        if self.step_y_mm <= 0.0 {
            return Err(ValidationError::NotPositive {
                field: "step_y_mm",
                value: self.step_y_mm,
            });
        }
        if !(2..=MAX_HEIGHT_MAP_AXIS_POINTS).contains(&self.columns) {
            return Err(ValidationError::OutOfRange {
                field: "columns",
                value: f64::from(self.columns),
                min: 2.0,
                max: f64::from(MAX_HEIGHT_MAP_AXIS_POINTS),
            });
        }
        if !(2..=MAX_HEIGHT_MAP_AXIS_POINTS).contains(&self.rows) {
            return Err(ValidationError::OutOfRange {
                field: "rows",
                value: f64::from(self.rows),
                min: 2.0,
                max: f64::from(MAX_HEIGHT_MAP_AXIS_POINTS),
            });
        }
        if self.point_count() > MAX_HEIGHT_MAP_POINTS {
            return Err(ValidationError::GridTooLarge {
                columns: u32::from(self.columns),
                rows: u32::from(self.rows),
                max_points: MAX_HEIGHT_MAP_POINTS,
            });
        }
        check_coordinate("surface_z_mm", self.surface_z_mm)?;
        let span_x = self.step_x_mm * f64::from(self.columns - 1);
        let span_y = self.step_y_mm * f64::from(self.rows - 1);
        check_coordinate("grid X span", span_x)?;
        check_coordinate("grid Y span", span_y)?;
        check_coordinate("grid maximum X", self.origin_mm.x_mm + span_x)?;
        check_coordinate("grid maximum Y", self.origin_mm.y_mm + span_y)?;
        Ok(())
    }

    /// Validate against shared probe parameters and the safe Z plane.
    ///
    /// The whole grid shares one vertical search: every point starts at safe Z
    /// and targets `surface_z_mm`. The travel `safe_z - surface_z` must be
    /// positive and no longer than `search_distance_mm`.
    pub fn validate_with_params(&self, params: &ProbeParams) -> Result<(), ValidationError> {
        params.validate()?;
        self.validate()?;
        let travel = params.safe_z_mm - self.surface_z_mm;
        check_finite("height-map travel", travel)?;
        if travel <= 0.0 {
            return Err(ValidationError::NotPositive {
                field: "height-map travel",
                value: travel,
            });
        }
        if travel > params.search_distance_mm {
            return Err(ValidationError::HeightMapTravel {
                travel_mm: travel,
                search_mm: params.search_distance_mm,
            });
        }
        Ok(())
    }

    /// Grid point for a column and row, or `None` when out of bounds.
    #[must_use]
    pub fn point(&self, column: u16, row: u16) -> Option<XyPoint> {
        if column >= self.columns || row >= self.rows {
            return None;
        }
        Some(XyPoint::new(
            self.origin_mm.x_mm + self.step_x_mm * f64::from(column),
            self.origin_mm.y_mm + self.step_y_mm * f64::from(row),
        ))
    }

    /// Linear index for a column and row.
    #[must_use]
    pub fn index(&self, column: u16, row: u16) -> Option<usize> {
        if column >= self.columns || row >= self.rows {
            return None;
        }
        Some(usize::from(row) * usize::from(self.columns) + usize::from(column))
    }

    /// Inclusive XY bounds of the grid.
    #[must_use]
    pub fn bounds(&self) -> Bounds2 {
        if self.columns == 0 || self.rows == 0 {
            return Bounds2::empty();
        }
        let max = XyPoint::new(
            self.origin_mm.x_mm + self.step_x_mm * f64::from(self.columns - 1),
            self.origin_mm.y_mm + self.step_y_mm * f64::from(self.rows - 1),
        );
        Bounds2::new(self.origin_mm.to_viewer(), max.to_viewer())
    }

    /// Returns `true` when the XY point is inside or on the grid.
    #[must_use]
    pub fn contains_xy(&self, x_mm: f64, y_mm: f64) -> bool {
        if !x_mm.is_finite() || !y_mm.is_finite() {
            return false;
        }
        let Some(max) = self.point(self.columns.saturating_sub(1), self.rows.saturating_sub(1))
        else {
            return false;
        };
        x_mm >= self.origin_mm.x_mm
            && x_mm <= max.x_mm
            && y_mm >= self.origin_mm.y_mm
            && y_mm <= max.y_mm
    }

    /// Build the complete height-map probing program with no probe-tip offset.
    ///
    /// This is [`HeightMapGrid::plan_with_offset`] with a zero offset.
    pub fn plan(&self, params: &ProbeParams) -> Result<ProbePlan, ProbeError> {
        self.plan_with_offset(params, XyPoint::new(0.0, 0.0))
    }

    /// Build the complete height-map probing program for a probe mounted away
    /// from the controlled point.
    ///
    /// Grid points are **feature / probe-tip** positions; every emitted XY
    /// rapid and `G38.2` target is the controlled point
    /// (`controlled = feature - offset`). Z is unchanged. The returned
    /// [`ProbePlan::probes`] positions are controlled-point machine
    /// coordinates.
    ///
    /// Points are visited row by row, X fastest. Every point retracts to safe Z
    /// (the rapid plane above the whole grid), moves in XY at safe Z, probes
    /// down with `G38.2` to `surface_z_mm`, then retracts and returns to safe Z.
    /// No rapid descends toward the work, so a locally higher surface is met by
    /// the probe feed, not by a G0. A missed point raises a controller alarm
    /// and stops the job, so later points never run on a bad probe. The offset
    /// must be finite and within [`crate::MAX_PROBE_OFFSET_MM`] on both axes.
    pub fn plan_with_offset(
        &self,
        params: &ProbeParams,
        offset: XyPoint,
    ) -> Result<ProbePlan, ProbeError> {
        validate_probe_offset(offset)?;
        self.validate_with_params(params)?;
        let mut builder = GcodeBuilder::new(params);
        for row in 0..self.rows {
            for column in 0..self.columns {
                let point = self
                    .point(column, row)
                    .ok_or(ProbeError::Degenerate("height-map grid point"))?;
                let controlled =
                    feature_to_controlled(Position::xyz(point.x_mm, point.y_mm, 0.0), offset);
                let x_mm = controlled.get(Axis::X);
                let y_mm = controlled.get(Axis::Y);
                builder.rapid_xy(x_mm, y_mm)?;
                let from = Position::xyz(x_mm, y_mm, params.safe_z_mm);
                let to = Position::xyz(x_mm, y_mm, self.surface_z_mm);
                builder.probe(format!("p{row}-c{column}"), from, to)?;
                builder.retract()?;
            }
        }
        builder.finish(crate::CycleKind::HeightMap, "height-map")
    }

    /// Estimate probing time for the preflight sheet.
    pub fn estimate(&self, params: &ProbeParams) -> Result<HeightMapEstimate, ProbeError> {
        self.validate_with_params(params)?;
        let points = self.point_count();
        let travel = params.safe_z_mm - self.surface_z_mm;
        let probe_seconds = travel / params.feed_mm_min * 60.0;
        let probing_seconds = probe_seconds * points as f64;
        let overhead_seconds = HEIGHT_MAP_POINT_OVERHEAD_SECONDS * points as f64;
        let total_seconds = probing_seconds + overhead_seconds;
        for (field, value) in [
            ("probing_seconds", probing_seconds),
            ("overhead_seconds", overhead_seconds),
            ("total_seconds", total_seconds),
        ] {
            check_finite(field, value)?;
        }
        Ok(HeightMapEstimate {
            points,
            probing_distance_mm: travel * points as f64,
            probing_seconds,
            overhead_seconds,
            total_seconds,
        })
    }
}

/// Estimated height-map duration.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct HeightMapEstimate {
    /// Number of points.
    pub points: usize,
    /// Total probing travel, in millimetres.
    pub probing_distance_mm: f64,
    /// Probing travel time, in seconds.
    pub probing_seconds: f64,
    /// Fixed per-point overhead, in seconds.
    pub overhead_seconds: f64,
    /// Estimated total, in seconds.
    pub total_seconds: f64,
}

/// Measured height grid with per-point validity.
///
/// Raw heights are machine Z coordinates from `PRB`. `None` means the point
/// was not probed, the probe failed, or the reported position was not finite.
/// Bilinear interpolation never bridges a missing point: a cell with a missing
/// corner returns `None`. The grid origin and the resulting bounds are also
/// machine XY.
///
/// A map may carry a constant Z datum shift (`z_offset_mm`, default zero).
/// [`HeightMap::samples`] and persistence keep the raw samples; display and
/// compensation APIs (`z`, `height_at`, `valid_points`, `z_range`, `summary`,
/// `csv`, `apply_to_z`, and `compensate_toolpath`) report
/// `raw + z_offset_mm`.
#[derive(Debug, Clone, PartialEq)]
pub struct HeightMap {
    grid: HeightMapGrid,
    samples: Vec<Option<f64>>,
    z_offset_mm: f64,
}

impl HeightMap {
    /// Build an empty, all-invalid map with a zero Z offset.
    pub fn new(grid: HeightMapGrid) -> Result<Self, ProbeError> {
        grid.validate()?;
        let samples = vec![None; grid.point_count()];
        Ok(HeightMap {
            grid,
            samples,
            z_offset_mm: 0.0,
        })
    }

    /// Build a map from explicit raw samples with a zero Z offset.
    pub fn from_samples(
        grid: HeightMapGrid,
        samples: Vec<Option<f64>>,
    ) -> Result<Self, ProbeError> {
        grid.validate()?;
        if samples.len() != grid.point_count() {
            return Err(ProbeError::ResultCount {
                expected: grid.point_count(),
                actual: samples.len(),
            });
        }
        for sample in samples.iter().flatten() {
            check_finite("height sample", *sample)?;
        }
        Ok(HeightMap {
            grid,
            samples,
            z_offset_mm: 0.0,
        })
    }

    /// Build a map from ordered probe results.
    ///
    /// A shorter result list is accepted as a partial map, for example when the
    /// operator stopped the cycle. Failed and non-finite results become invalid
    /// cells. Extra results are rejected.
    pub fn from_results(grid: HeightMapGrid, results: &[ProbeResult]) -> Result<Self, ProbeError> {
        grid.validate()?;
        let count = grid.point_count();
        if results.len() > count {
            return Err(ProbeError::ResultCount {
                expected: count,
                actual: results.len(),
            });
        }
        let mut map = HeightMap::new(grid)?;
        for (index, result) in results.iter().enumerate() {
            if result.success
                && result.position.is_finite()
                && result.position.axes().contains(Axis::Z)
            {
                map.samples[index] = Some(result.position.get(Axis::Z));
            }
        }
        Ok(map)
    }

    /// Set a constant Z datum offset, consuming and returning the map.
    ///
    /// The offset is added to every raw sample by display and compensation
    /// APIs; [`HeightMap::samples`] keeps the raw values for persistence and
    /// audit. It must be finite and within
    /// `+/-` [`MAX_HEIGHT_MAP_Z_OFFSET_MM`].
    pub fn with_z_offset(mut self, z_offset_mm: f64) -> Result<Self, ProbeError> {
        self.set_z_offset(z_offset_mm)?;
        Ok(self)
    }

    /// Set a constant Z datum offset in place.
    ///
    /// See [`HeightMap::with_z_offset`] for the effective/raw split.
    pub fn set_z_offset(&mut self, z_offset_mm: f64) -> Result<(), ProbeError> {
        check_range(
            "z_offset_mm",
            z_offset_mm,
            -MAX_HEIGHT_MAP_Z_OFFSET_MM,
            MAX_HEIGHT_MAP_Z_OFFSET_MM,
        )?;
        self.z_offset_mm = z_offset_mm;
        Ok(())
    }

    /// Constant Z datum offset added to every raw sample, in millimetres.
    #[must_use]
    pub fn z_offset_mm(&self) -> f64 {
        self.z_offset_mm
    }

    /// Grid definition.
    #[must_use]
    pub fn grid(&self) -> &HeightMapGrid {
        &self.grid
    }

    /// Every raw sample in row-major order; `None` is invalid.
    ///
    /// These are the measured machine Z values before
    /// [`HeightMap::z_offset_mm`]. Persist these values together with the
    /// offset; the display/compensation APIs apply the offset.
    #[must_use]
    pub fn samples(&self) -> &[Option<f64>] {
        &self.samples
    }

    /// Number of cells.
    #[must_use]
    pub fn len(&self) -> usize {
        self.samples.len()
    }

    /// Always `false`; present for the standard collection API.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.samples.is_empty()
    }

    /// Effective sample at a grid point: raw sample plus
    /// [`HeightMap::z_offset_mm`].
    ///
    /// Returns `None` for an invalid cell. Use [`HeightMap::samples`] for the
    /// unchanged raw values.
    #[must_use]
    pub fn z(&self, column: u16, row: u16) -> Option<f64> {
        self.raw_z(column, row)
            .map(|raw| self.effective_height(raw))
    }

    /// Raw sample at a grid point, before the Z offset.
    fn raw_z(&self, column: u16, row: u16) -> Option<f64> {
        let index = self.grid.index(column, row)?;
        self.samples.get(index).copied().flatten()
    }

    /// Apply the map's constant datum shift to one raw height.
    fn effective_height(&self, raw_mm: f64) -> f64 {
        if self.z_offset_mm == 0.0 {
            raw_mm
        } else {
            raw_mm + self.z_offset_mm
        }
    }

    /// Set or invalidate one cell.
    pub fn set_z(&mut self, column: u16, row: u16, value: Option<f64>) -> Result<(), ProbeError> {
        let index = self
            .grid
            .index(column, row)
            .ok_or(ProbeError::Degenerate("height-map index"))?;
        if let Some(height) = value {
            check_finite("height sample", height)?;
        }
        self.samples[index] = value;
        Ok(())
    }

    /// Invalidate one cell.
    pub fn invalidate(&mut self, column: u16, row: u16) -> Result<(), ProbeError> {
        self.set_z(column, row, None)
    }

    /// Number of valid cells.
    #[must_use]
    pub fn valid_count(&self) -> usize {
        self.samples.iter().flatten().count()
    }

    /// Number of invalid cells.
    #[must_use]
    pub fn missing_count(&self) -> usize {
        self.len() - self.valid_count()
    }

    /// Returns `true` when every cell is valid.
    #[must_use]
    pub fn is_complete(&self) -> bool {
        self.missing_count() == 0
    }

    /// Inclusive XY bounds of the grid, in machine coordinates.
    #[must_use]
    pub fn bounds(&self) -> Bounds2 {
        self.grid.bounds()
    }

    /// Returns `true` when the XY point is inside or on the grid.
    #[must_use]
    pub fn contains(&self, x_mm: f64, y_mm: f64) -> bool {
        self.grid.contains_xy(x_mm, y_mm)
    }

    /// Bilinearly interpolated effective height.
    ///
    /// Returns the interpolated raw sample plus [`HeightMap::z_offset_mm`].
    /// Returns `None` outside the grid or when a required sample is invalid.
    /// On a grid line only the samples that actually contribute are required.
    #[must_use]
    pub fn height_at(&self, x_mm: f64, y_mm: f64) -> Option<f64> {
        self.raw_height_at(x_mm, y_mm)
            .map(|raw| self.effective_height(raw))
    }

    fn raw_height_at(&self, x_mm: f64, y_mm: f64) -> Option<f64> {
        if !self.grid.contains_xy(x_mm, y_mm) {
            return None;
        }
        let grid = &self.grid;
        let max_column = f64::from(grid.columns.saturating_sub(1));
        let max_row = f64::from(grid.rows.saturating_sub(1));
        let fx = ((x_mm - grid.origin_mm.x_mm) / grid.step_x_mm).clamp(0.0, max_column);
        let fy = ((y_mm - grid.origin_mm.y_mm) / grid.step_y_mm).clamp(0.0, max_row);
        let column0 = fx.floor();
        let row0 = fy.floor();
        let column0 = column0 as u16;
        let row0 = row0 as u16;
        let column1 = (column0 + 1).min(grid.columns.saturating_sub(1));
        let row1 = (row0 + 1).min(grid.rows.saturating_sub(1));
        let tx = fx - f64::from(column0);
        let ty = fy - f64::from(row0);
        let epsilon = 1e-12;

        let z00 = self.raw_z(column0, row0)?;
        if tx.abs() <= epsilon && ty.abs() <= epsilon {
            return Some(z00);
        }
        if tx.abs() <= epsilon {
            let z01 = self.raw_z(column0, row1)?;
            return Some(z00 * (1.0 - ty) + z01 * ty);
        }
        if ty.abs() <= epsilon {
            let z10 = self.raw_z(column1, row0)?;
            return Some(z00 * (1.0 - tx) + z10 * tx);
        }
        let z10 = self.raw_z(column1, row0)?;
        let z01 = self.raw_z(column0, row1)?;
        let z11 = self.raw_z(column1, row1)?;
        let bottom = z00 * (1.0 - tx) + z10 * tx;
        let top = z01 * (1.0 - tx) + z11 * tx;
        Some(bottom * (1.0 - ty) + top * ty)
    }

    /// Z compensation at an XY point: effective measured surface minus the
    /// nominal surface.
    ///
    /// The map's [`HeightMap::z_offset_mm`] is part of the effective height,
    /// so it shifts compensation by exactly the offset.
    #[must_use]
    pub fn compensation_at(&self, x_mm: f64, y_mm: f64) -> Option<f64> {
        let height = self.height_at(x_mm, y_mm)?;
        Some(height - self.grid.surface_z_mm)
    }

    /// Apply height compensation to a nominal program Z.
    ///
    /// `x_mm` and `y_mm` are machine coordinates for the lookup. `z_mm` is the
    /// nominal program Z; only the effective measured deviation (including
    /// [`HeightMap::z_offset_mm`]) is added, so its frame cancels. This is the
    /// primitive for streamed compensation; a corrected G-code export is a
    /// follow-up.
    #[must_use]
    pub fn apply_to_z(&self, x_mm: f64, y_mm: f64, z_mm: f64) -> Option<f64> {
        if !z_mm.is_finite() {
            return None;
        }
        Some(z_mm + self.compensation_at(x_mm, y_mm)?)
    }

    /// Apply this map to every segment of a viewer toolpath.
    ///
    /// # Coordinates
    ///
    /// The toolpath is in **work coordinates**, in millimetres. Height lookups
    /// are machine XY, so every sample is converted with
    /// `machine = work + work_offset`. Z needs no offset: the effective
    /// deviation `(measured Z + z_offset) - nominal surface Z` is
    /// frame-independent, so it is added directly to the work Z.
    ///
    /// # Subdivision
    ///
    /// Moves are split at no more than half the smaller grid step
    /// ([`HeightMapGrid::step_x_mm`] or [`HeightMapGrid::step_y_mm`]), so the
    /// compensation follows the surface along the move instead of changing
    /// only at its endpoints. Subdivision is bounded by
    /// [`MAX_COMPENSATED_SEGMENTS`]; after that budget every remaining input
    /// segment is copied as a single piece and still receives endpoint
    /// compensation when both endpoints have values. An all-invalid map, or a
    /// move whose XY bounding box cannot touch the grid, is not subdivided
    /// because no sample could provide a value.
    ///
    /// Every output segment keeps the source [`Segment::kind`],
    /// [`Segment::layer`], and [`Segment::tool`], including rapids and Z-only
    /// moves. The output order matches the input order. A straight move is
    /// preserved geometrically; its Z is the linearly interpolated nominal Z
    /// plus the sampled deviation.
    ///
    /// # Uncompensated geometry
    ///
    /// A generated segment is compensated only when both of its sample points
    /// have a value. A point has no value outside the grid, across a missing
    /// cell, or when the work offset is non-finite. Such segments keep their
    /// nominal Z and are counted in
    /// [`CompensatedToolpath::uncompensated_segments`] and
    /// [`CompensatedToolpath::uncompensated_length_mm`]; the map never invents
    /// a nearby value or bridges an invalid cell. A path that leaves and later
    /// re-enters the grid can therefore be discontinuous in Z at a missing
    /// sample.
    ///
    /// # Limitations
    ///
    /// Only an XY work offset is modelled. Work-plane rotation, axis scaling,
    /// and machine tilt are **not** applied; feed them into the toolpath
    /// before calling this method or compensate in a later layer. The map's
    /// own [`HeightMap::z_offset_mm`] **is** applied through
    /// [`HeightMap::compensation_at`].
    ///
    /// All lengths are millimetres. The source toolpath is not modified.
    #[must_use]
    pub fn compensate_toolpath(
        &self,
        toolpath: &Toolpath,
        work_offset: Point2,
    ) -> CompensatedToolpath {
        self.compensate_toolpath_with_budget(toolpath, work_offset, MAX_COMPENSATED_SEGMENTS)
    }

    /// Internal form with an explicit subdivision budget, used by tests and by
    /// [`HeightMap::compensate_toolpath`].
    fn compensate_toolpath_with_budget(
        &self,
        toolpath: &Toolpath,
        work_offset: Point2,
        max_segments: usize,
    ) -> CompensatedToolpath {
        let source = toolpath.segments();
        if source.is_empty() {
            return CompensatedToolpath::default();
        }

        // No cell can provide a value, so there is nothing to sample. Keep the
        // source path exactly as supplied instead of rebuilding it.
        if self.valid_count() == 0 {
            return CompensatedToolpath {
                toolpath: toolpath.clone(),
                compensated_segments: 0,
                uncompensated_segments: source.len(),
                compensated_length_mm: 0.0,
                uncompensated_length_mm: source.iter().map(segment_length_mm).sum(),
            };
        }

        let spacing_mm = self.compensation_spacing_mm();
        let mut result = CompensatedToolpath {
            toolpath: Toolpath::with_capacity(source.len()),
            compensated_segments: 0,
            uncompensated_segments: 0,
            compensated_length_mm: 0.0,
            uncompensated_length_mm: 0.0,
        };
        let mut budget = max_segments;

        for segment in source {
            if !segment.is_valid() {
                // `Toolpath` rejects non-finite geometry, but keep the
                // accounting total safe if one reaches here by another route.
                result.uncompensated_segments += 1;
                result.uncompensated_length_mm += segment_length_mm(segment);
                continue;
            }

            let desired_parts = self.desired_parts(segment, work_offset, spacing_mm);
            let parts = desired_parts.min(budget.max(1));
            budget = budget.saturating_sub(parts);

            let nominal_length_mm = segment_length_mm(segment);
            let part_length_mm = if nominal_length_mm.is_finite() && parts > 0 {
                nominal_length_mm / parts as f64
            } else {
                0.0
            };

            self.push_compensated(segment, work_offset, parts, part_length_mm, &mut result);
        }

        result
    }

    /// Sample spacing along a move, in millimetres.
    fn compensation_spacing_mm(&self) -> f64 {
        let spacing = self.grid.step_x_mm.min(self.grid.step_y_mm) * COMPENSATION_SAMPLE_FRACTION;
        if spacing.is_finite() && spacing > 0.0 {
            spacing
        } else {
            f64::INFINITY
        }
    }

    /// Number of pieces for one segment, capped before any allocation.
    fn desired_parts(&self, segment: &Segment, work_offset: Point2, spacing_mm: f64) -> usize {
        if !spacing_mm.is_finite() || spacing_mm <= 0.0 {
            return 1;
        }
        let (x0, y0) = machine_xy(segment.start, work_offset);
        let (x1, y1) = machine_xy(segment.end, work_offset);
        if !x0.is_finite() || !y0.is_finite() || !x1.is_finite() || !y1.is_finite() {
            return 1;
        }
        let xy_length_mm = ((x1 - x0).powi(2) + (y1 - y0).powi(2)).sqrt();
        if !xy_length_mm.is_finite() || xy_length_mm <= 0.0 {
            return 1;
        }
        // The bounding-box test keeps a path that cannot touch the grid from
        // being subdivided at all.
        if !self.segment_may_intersect_grid(x0, y0, x1, y1) {
            return 1;
        }
        let desired = (xy_length_mm / spacing_mm).ceil();
        if !desired.is_finite() || desired <= 1.0 {
            return 1;
        }
        // Clamp in f64 before the cast so an extreme but finite coordinate
        // never requests an unbounded allocation.
        if desired >= MAX_COMPENSATED_SEGMENTS as f64 {
            MAX_COMPENSATED_SEGMENTS
        } else {
            desired as usize
        }
    }

    /// Returns `true` when the segment's XY bounding box overlaps the grid.
    fn segment_may_intersect_grid(&self, x0: f64, y0: f64, x1: f64, y1: f64) -> bool {
        let grid = &self.grid;
        let max_x =
            grid.origin_mm.x_mm + grid.step_x_mm * f64::from(grid.columns.saturating_sub(1));
        let max_y = grid.origin_mm.y_mm + grid.step_y_mm * f64::from(grid.rows.saturating_sub(1));
        let segment_min_x = x0.min(x1);
        let segment_max_x = x0.max(x1);
        let segment_min_y = y0.min(y1);
        let segment_max_y = y0.max(y1);
        segment_max_x >= grid.origin_mm.x_mm
            && segment_min_x <= max_x
            && segment_max_y >= grid.origin_mm.y_mm
            && segment_min_y <= max_y
    }

    /// Subdivide one input segment and append its output pieces.
    fn push_compensated(
        &self,
        segment: &Segment,
        work_offset: Point2,
        parts: usize,
        part_length_mm: f64,
        result: &mut CompensatedToolpath,
    ) {
        let parts = parts.max(1);
        let start_z_mm = f64::from(segment.start.z);
        let end_z_mm = f64::from(segment.end.z);
        let mut previous: Option<CompensationSample> = None;

        for index in 0..=parts {
            let t = index as f64 / parts as f64;
            let sample = if index == 0 {
                self.sample_at(segment.start.x, segment.start.y, start_z_mm, work_offset)
            } else if index == parts {
                self.sample_at(segment.end.x, segment.end.y, end_z_mm, work_offset)
            } else {
                let x = f64::from(segment.start.x)
                    + (f64::from(segment.end.x) - f64::from(segment.start.x)) * t;
                let y = f64::from(segment.start.y)
                    + (f64::from(segment.end.y) - f64::from(segment.start.y)) * t;
                let nominal_z_mm = start_z_mm + (end_z_mm - start_z_mm) * t;
                CompensationSample {
                    x: x as f32,
                    y: y as f32,
                    nominal_z_mm,
                    compensation_mm: self.compensation_at(
                        x + f64::from(work_offset.x),
                        y + f64::from(work_offset.y),
                    ),
                }
            };

            if let Some(previous) = previous {
                self.push_piece(previous, sample, segment, part_length_mm, result);
            }
            previous = Some(sample);
        }
    }

    /// Build one sample point and look up its compensation.
    fn sample_at(
        &self,
        x: f32,
        y: f32,
        nominal_z_mm: f64,
        work_offset: Point2,
    ) -> CompensationSample {
        CompensationSample {
            x,
            y,
            nominal_z_mm,
            compensation_mm: self.compensation_at(
                f64::from(x) + f64::from(work_offset.x),
                f64::from(y) + f64::from(work_offset.y),
            ),
        }
    }

    /// Append one output piece and update the accounting.
    fn push_piece(
        &self,
        start: CompensationSample,
        end: CompensationSample,
        source: &Segment,
        part_length_mm: f64,
        result: &mut CompensatedToolpath,
    ) {
        let compensated =
            start
                .compensation_mm
                .zip(end.compensation_mm)
                .and_then(|(start_comp, end_comp)| {
                    let start_z_mm = start.nominal_z_mm + start_comp;
                    let end_z_mm = end.nominal_z_mm + end_comp;
                    Some((finite_f32(start_z_mm)?, finite_f32(end_z_mm)?))
                });
        let (start_z, end_z, applied) = match compensated {
            Some((start_z, end_z)) => (start_z, end_z, true),
            None => (
                finite_f32(start.nominal_z_mm).unwrap_or(0.0),
                finite_f32(end.nominal_z_mm).unwrap_or(0.0),
                false,
            ),
        };

        let piece = Segment {
            start: Point3::new(start.x, start.y, start_z),
            end: Point3::new(end.x, end.y, end_z),
            layer: source.layer,
            tool: source.tool,
            kind: source.kind,
        };
        if result.toolpath.push(piece) {
            if applied {
                result.compensated_segments += 1;
                result.compensated_length_mm += part_length_mm;
            } else {
                result.uncompensated_segments += 1;
                result.uncompensated_length_mm += part_length_mm;
            }
        } else {
            // Non-finite output cannot enter a `Toolpath`; count it honestly
            // rather than silently losing length.
            result.uncompensated_segments += 1;
            result.uncompensated_length_mm += part_length_mm;
        }
    }

    /// Valid samples as machine-XY viewer overlay points with their effective
    /// height (raw sample plus [`HeightMap::z_offset_mm`]).
    #[must_use]
    pub fn valid_points(&self) -> Vec<(Point2, f64)> {
        let mut points = Vec::with_capacity(self.valid_count());
        for row in 0..self.grid.rows {
            for column in 0..self.grid.columns {
                let Some(height) = self.z(column, row) else {
                    continue;
                };
                let Some(point) = self.grid.point(column, row) else {
                    continue;
                };
                points.push((point.to_viewer(), height));
            }
        }
        points
    }

    /// Lowest and highest effective valid height, if any.
    ///
    /// The range includes [`HeightMap::z_offset_mm`].
    #[must_use]
    pub fn z_range(&self) -> Option<(f64, f64)> {
        let mut range: Option<(f64, f64)> = None;
        for height in self.samples.iter().flatten() {
            let effective = self.effective_height(*height);
            range = Some(match range {
                Some((low, high)) => (low.min(effective), high.max(effective)),
                None => (effective, effective),
            });
        }
        range
    }

    /// One row of raw samples, before [`HeightMap::z_offset_mm`].
    ///
    /// Use [`HeightMap::z`] for an effective value.
    #[must_use]
    pub fn row(&self, row: u16) -> Option<&[Option<f64>]> {
        if row >= self.grid.rows {
            return None;
        }
        let start = usize::from(row) * usize::from(self.grid.columns);
        let end = start + usize::from(self.grid.columns);
        self.samples.get(start..end)
    }

    /// Counts and height/compensation ranges for the whole map.
    ///
    /// The ranges are `None` when no cell is valid; an all-invalid map still
    /// reports its point count and missing count. Every value is in millimetres
    /// and compensation is `effective Z - nominal surface Z`, where the
    /// effective Z includes [`HeightMap::z_offset_mm`].
    #[must_use]
    pub fn summary(&self) -> HeightMapSummary {
        let valid_points = self.valid_count();
        let mut min_z_mm = f64::INFINITY;
        let mut max_z_mm = f64::NEG_INFINITY;
        let mut min_compensation_mm = f64::INFINITY;
        let mut max_compensation_mm = f64::NEG_INFINITY;

        for height in self.samples.iter().flatten() {
            let effective = self.effective_height(*height);
            let compensation_mm = effective - self.grid.surface_z_mm;
            min_z_mm = min_z_mm.min(effective);
            max_z_mm = max_z_mm.max(effective);
            min_compensation_mm = min_compensation_mm.min(compensation_mm);
            max_compensation_mm = max_compensation_mm.max(compensation_mm);
        }

        let has_valid = valid_points > 0;
        HeightMapSummary {
            points: self.len(),
            valid_points,
            missing_points: self.len() - valid_points,
            min_z_mm: has_valid.then_some(min_z_mm),
            max_z_mm: has_valid.then_some(max_z_mm),
            min_compensation_mm: has_valid.then_some(min_compensation_mm),
            max_compensation_mm: has_valid.then_some(max_compensation_mm),
        }
    }

    /// Export the map as a compact CSV string.
    ///
    /// The first line is always
    /// `column,row,x_mm,y_mm,z_mm,valid`, followed by exactly
    /// [`HeightMap::len`] rows in stable row-major order (row outer, column
    /// inner). `x_mm`, `y_mm`, and valid `z_mm` values use six decimal places.
    /// `z_mm` is the **effective** height: raw sample plus
    /// [`HeightMap::z_offset_mm`]. An invalid cell leaves the `z_mm` field
    /// empty and writes `valid` as `0`; valid cells write `valid` as `1`. The
    /// output ends with a newline and has no quoting because every field is
    /// numeric. No file is written; persist [`HeightMap::samples`] and the
    /// offset separately to round-trip the raw data.
    #[must_use]
    pub fn csv(&self) -> String {
        use std::fmt::Write as _;

        let mut output = String::with_capacity(64 + self.len().saturating_mul(48));
        output.push_str("column,row,x_mm,y_mm,z_mm,valid\n");
        for row in 0..self.grid.rows {
            for column in 0..self.grid.columns {
                let Some(point) = self.grid.point(column, row) else {
                    continue;
                };
                match self.z(column, row) {
                    Some(height) => {
                        let _ = writeln!(
                            output,
                            "{column},{row},{:.6},{:.6},{height:.6},1",
                            point.x_mm, point.y_mm
                        );
                    }
                    None => {
                        let _ = writeln!(
                            output,
                            "{column},{row},{:.6},{:.6},,0",
                            point.x_mm, point.y_mm
                        );
                    }
                }
            }
        }
        output
    }
}

/// One sampled point along a source segment while compensating.
#[derive(Debug, Clone, Copy)]
struct CompensationSample {
    /// Work X, in millimetres.
    x: f32,
    /// Work Y, in millimetres.
    y: f32,
    /// Nominal work Z before compensation, in millimetres.
    nominal_z_mm: f64,
    /// Measured deviation at the machine XY, or `None` when unavailable.
    compensation_mm: Option<f64>,
}

/// Result of applying a [`HeightMap`] to a [`Toolpath`].
///
/// The output path preserves input order and every segment's kind, layer, and
/// tool. Lengths partition the input path's nominal length: a segment that was
/// split contributes its full length to one category per output piece, and
/// `compensated_length_mm + uncompensated_length_mm` equals the source length
/// (apart from floating-point rounding).
#[derive(Debug, Clone, Default, PartialEq)]
pub struct CompensatedToolpath {
    /// Compensated output path. Every source segment is represented.
    pub toolpath: Toolpath,
    /// Number of output segments that received a measured deviation.
    pub compensated_segments: usize,
    /// Number of output segments left at their nominal Z.
    pub uncompensated_segments: usize,
    /// Source path length attributed to compensated output segments, in
    /// millimetres.
    pub compensated_length_mm: f64,
    /// Source path length attributed to uncompensated output segments, in
    /// millimetres.
    pub uncompensated_length_mm: f64,
}

impl CompensatedToolpath {
    /// Total number of output segments.
    #[must_use]
    pub fn total_segments(&self) -> usize {
        self.compensated_segments + self.uncompensated_segments
    }

    /// Total source path length, in millimetres.
    #[must_use]
    pub fn total_length_mm(&self) -> f64 {
        self.compensated_length_mm + self.uncompensated_length_mm
    }

    /// Returns `true` when no output segment was left uncompensated.
    ///
    /// An empty path is fully compensated because it has nothing to leave
    /// unchanged.
    #[must_use]
    pub fn is_fully_compensated(&self) -> bool {
        self.uncompensated_segments == 0
    }
}

/// Counts and ranges for a [`HeightMap`].
///
/// A range is `None` only when the map contains no valid cell. Height ranges
/// are effective values, including [`HeightMap::z_offset_mm`].
#[derive(Debug, Clone, Copy, Default, PartialEq)]
pub struct HeightMapSummary {
    /// Total number of grid points.
    pub points: usize,
    /// Points with an effective height.
    pub valid_points: usize,
    /// Points without a measured height.
    pub missing_points: usize,
    /// Lowest valid effective Z, in machine millimetres.
    pub min_z_mm: Option<f64>,
    /// Highest valid effective Z, in machine millimetres.
    pub max_z_mm: Option<f64>,
    /// Lowest valid effective compensation, in millimetres.
    pub min_compensation_mm: Option<f64>,
    /// Highest valid effective compensation, in millimetres.
    pub max_compensation_mm: Option<f64>,
}

impl HeightMapSummary {
    /// Returns `true` when the map has no valid point.
    #[must_use]
    pub fn is_all_invalid(&self) -> bool {
        self.valid_points == 0
    }

    /// Returns `true` when every point is valid.
    #[must_use]
    pub fn is_complete(&self) -> bool {
        self.missing_points == 0
    }
}

/// Nominal 3D length of one source segment, in millimetres.
fn segment_length_mm(segment: &Segment) -> f64 {
    let dx = f64::from(segment.end.x) - f64::from(segment.start.x);
    let dy = f64::from(segment.end.y) - f64::from(segment.start.y);
    let dz = f64::from(segment.end.z) - f64::from(segment.start.z);
    (dx * dx + dy * dy + dz * dz).sqrt()
}

/// Work XY of a point converted to machine XY.
fn machine_xy(point: Point3, work_offset: Point2) -> (f64, f64) {
    (
        f64::from(point.x) + f64::from(work_offset.x),
        f64::from(point.y) + f64::from(work_offset.y),
    )
}

/// Converts a compensated Z to `f32`, rejecting values that would become
/// non-finite in the viewer's coordinate type.
fn finite_f32(value: f64) -> Option<f32> {
    let value = value as f32;
    value.is_finite().then_some(value)
}

#[cfg(test)]
mod tests {
    use super::*;
    use ghs_viewer::SegmentKind;

    #[test]
    fn compensation_budget_caps_subdivision_but_keeps_every_input_segment() {
        let map = HeightMap::from_samples(
            HeightMapGrid {
                origin_mm: XyPoint::new(0.0, 0.0),
                step_x_mm: 1_000.0,
                step_y_mm: 1_000.0,
                columns: 2,
                rows: 2,
                surface_z_mm: 0.0,
            },
            vec![Some(0.0); 4],
        )
        .expect("valid map");
        let mut source = Toolpath::new();
        source.append_line(
            Point3::new(0.0, 0.0, 0.0),
            Point3::new(1_000.0, 0.0, 0.0),
            SegmentKind::Feed,
            0,
            0,
        );
        source.append_line(
            Point3::new(0.0, 0.0, 0.0),
            Point3::new(1_000.0, 0.0, 0.0),
            SegmentKind::Feed,
            0,
            0,
        );

        let result = map.compensate_toolpath_with_budget(&source, Point2::ZERO, 3);
        assert_eq!(result.toolpath.len(), 3);
        assert_eq!(result.total_segments(), 3);
        assert!((result.total_length_mm() - 2_000.0).abs() < 1e-9);
        let segments = result.toolpath.segments();
        assert!(
            segments[..2]
                .iter()
                .all(|segment| segment.start.x <= 1_000.0)
        );
        assert_eq!(segments[2].start, source.segments()[1].start);
        assert_eq!(segments[2].end, source.segments()[1].end);
        assert_eq!((segments[0].start.x, segments[0].end.x), (0.0, 500.0));
        assert_eq!((segments[1].start.x, segments[1].end.x), (500.0, 1_000.0));
    }
}
